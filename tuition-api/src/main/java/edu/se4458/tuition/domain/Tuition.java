package edu.se4458.tuition.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.type.SqlTypes;

/** Tuition of one student for one term. Unique per (student, term). */
@Entity
@Table(name = "tuitions")
public class Tuition {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "student_no", nullable = false)
    private Student student;

    @Column(name = "term", nullable = false, length = 11)
    private String term;

    @Column(name = "amount", nullable = false, precision = 12, scale = 2)
    private BigDecimal amount;

    @Column(name = "paid_amount", nullable = false, precision = 12, scale = 2)
    private BigDecimal paidAmount;

    /**
     * Generated by the database (amount - paid_amount). Mapped read-only so queries can filter on it;
     * business logic uses {@link #outstandingBalance()} instead, which is always up to date in memory.
     */
    @Column(name = "balance", insertable = false, updatable = false, precision = 12, scale = 2)
    private BigDecimal balance;

    @JdbcTypeCode(SqlTypes.CHAR)
    @Column(name = "currency", nullable = false, length = 3)
    private String currency;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Tuition() {
    }

    public Tuition(Student student, String term, BigDecimal amount, String currency) {
        this.student = student;
        this.term = term;
        this.amount = amount;
        this.paidAmount = Money.ZERO;
        this.currency = currency;
    }

    public BigDecimal outstandingBalance() {
        return amount.subtract(paidAmount);
    }

    /** Sets a new total amount and currency. Callers check the business rules first. */
    public void update(BigDecimal newAmount, String newCurrency) {
        this.amount = newAmount;
        this.currency = newCurrency;
    }

    /** Adds a payment to the paid amount. Callers check that it does not exceed the balance. */
    public void recordPayment(BigDecimal paymentAmount) {
        this.paidAmount = this.paidAmount.add(paymentAmount);
    }

    public Long getId() {
        return id;
    }

    public Student getStudent() {
        return student;
    }

    public String getTerm() {
        return term;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public BigDecimal getPaidAmount() {
        return paidAmount;
    }

    public String getCurrency() {
        return currency;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
